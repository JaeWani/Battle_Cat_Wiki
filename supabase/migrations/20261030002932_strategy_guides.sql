create function noc_private.guide_int(value jsonb,low integer,high integer)returns integer language plpgsql security invoker set search_path='' as $$begin
 if jsonb_typeof(value) is distinct from 'number' or value::text !~ '^[0-9]+$' or (value::text)::numeric not between low and high then raise exception '공략 숫자 범위를 확인해 주세요.';end if;return (value::text)::integer;end$$;
create function noc_private.store_strategy(identifier uuid,raw jsonb)returns void language plpgsql security invoker set search_path='' as $$
declare row noc_private.posts;stage text;map text;stage_index integer;crown_num integer;outcome_name text;unit jsonb;talent jsonb;clean jsonb:='[]';talents jsonb;seen integer[]:='{}';talent_seen integer[];id_num integer;form_num integer;lv integer;plus_num integer;t_id integer;t_lv integer;max_lv integer;role_name text;conditions jsonb:='{}';k text;v text;items jsonb:='[]';entry jsonb;result jsonb;
begin
 select * into row from noc_private.posts where id=identifier for update;
 if auth.uid() is null or not noc_private.active_member() or row.author_id is distinct from auth.uid() or row.status<>'published' then raise exception '작성자 권한이 필요합니다.';end if;
 if raw='null'::jsonb then delete from noc_private.strategy_guides where post_id=identifier;return;end if;
 if row.board<>'guide' or jsonb_typeof(raw) is distinct from 'object' or raw->'publishAccepted' is distinct from 'true'::jsonb or octet_length(raw::text)>20000 then raise exception '공략 공개 항목을 확인해 주세요.';end if;
 stage:=raw->>'stageKey';if stage is null or stage !~ '^[A-Z]{1,2}[0-9]{3}-[0-9]{1,3}$' then raise exception '스테이지를 선택해 주세요.';end if;
 map:=split_part(stage,'-',1);stage_index:=split_part(stage,'-',2)::integer;
 if stage<>map||'-'||stage_index or not exists(select 1 from noc_private.guide_maps where code=map and stage_index<stage_count)then raise exception '미등록 스테이지입니다.';end if;
 crown_num:=noc_private.guide_int(raw->'crown',1,4);outcome_name:=raw->>'outcome';
 if raw->>'region' is distinct from 'kr' or outcome_name is null or outcome_name not in('clear','failed','testing') then raise exception '한국판 공략과 결과를 선택해 주세요.';end if;
 if jsonb_typeof(raw->'lineup') is distinct from 'array' or jsonb_array_length(raw->'lineup') not between 1 and 10 then raise exception '편성은 1~10종입니다.';end if;
 for unit in select value from jsonb_array_elements(raw->'lineup')loop
  id_num:=noc_private.guide_int(unit->'id',0,9999);form_num:=noc_private.guide_int(unit->'form',0,3);lv:=noc_private.guide_int(unit->'level',1,200);plus_num:=noc_private.guide_int(unit->'plus',0,1000);role_name:=unit->>'role';
  if id_num=any(seen) or not exists(select 1 from noc_private.characters where key='c'||id_num||'-'||form_num and kind='cat')or role_name is null or role_name not in('frontline','damage','control','utility')then raise exception '편성 캐릭터·형태·역할을 확인해 주세요.';end if;seen:=array_append(seen,id_num);
  talents:='null';talent_seen:='{}';if jsonb_typeof(unit->'talents') is distinct from 'null' and unit ? 'talents' then
   if jsonb_typeof(unit->'talents') is distinct from 'array' or jsonb_array_length(unit->'talents')>16 then raise exception '본능 형식을 확인해 주세요.';end if;talents:='[]';
   for talent in select value from jsonb_array_elements(unit->'talents')loop
    t_id:=noc_private.guide_int(talent->'id',1,255);t_lv:=noc_private.guide_int(talent->'level',0,10);select max_level into max_lv from noc_private.character_talents where cat_id=id_num and ability_id=t_id;
    if max_lv is null or t_lv>max_lv or t_id=any(talent_seen)then raise exception '캐릭터별 본능 상한을 확인해 주세요.';end if;talent_seen:=array_append(talent_seen,t_id);talents:=talents||jsonb_build_array(jsonb_build_object('id',t_id,'level',t_lv));
   end loop;
  end if;
  clean:=clean||jsonb_build_array(jsonb_build_object('id',id_num,'form',form_num,'level',lv,'plus',plus_num,'talents',talents,'role',role_name));
 end loop;
 foreach k in array array['world','future','cosmos']loop v:=raw->'treasures'->>k;if v is null or v not in('max','any','unknown')then raise exception '보물 조건을 확인해 주세요.';end if;conditions:=conditions||jsonb_build_object(k,v);end loop;
 if jsonb_typeof(raw->'items') is distinct from 'array' or jsonb_array_length(raw->'items')>6 then raise exception '아이템 조건을 확인해 주세요.';end if;
 for entry in select value from jsonb_array_elements(raw->'items')loop
  v:=entry#>>'{}';if jsonb_typeof(entry)<>'string' or v not in('speed','radar','rich','cpu','jobs','sniper') or items @>jsonb_build_array(v) then raise exception '미등록·중복 아이템입니다.';end if;items:=items||jsonb_build_array(v);
 end loop;
 result:=jsonb_build_object('schemaVersion',1,'region','kr','stageKey',stage,'crown',crown_num,'outcome',outcome_name,'lineup',clean,'treasures',conditions,'items',items);
 insert into noc_private.strategy_guides(post_id,details,stage_key,crown,outcome,updated_at)values(identifier,result,stage,crown_num,outcome_name,clock_timestamp())on conflict(post_id)do update set details=excluded.details,stage_key=excluded.stage_key,crown=excluded.crown,outcome=excluded.outcome,updated_at=excluded.updated_at;
end$$;
create function noc_private.guide_distance(lineup jsonb,cats jsonb)returns numeric language sql immutable security invoker set search_path='' as $$
 select coalesce(avg(case when owned is null then 1000 else abs((slot->>'level')::int+(slot->>'plus')::int-(owned->>'level')::int-(owned->>'plus')::int)+case when (owned->>'form')::int<(slot->>'form')::int then 20 else 0 end+coalesce((select sum(case when own_t is null then 10 else abs((needed->>'level')::int-(own_t->>'level')::int)*5 end)from jsonb_array_elements(case when jsonb_typeof(slot->'talents')='array' then slot->'talents' else '[]' end)needed left join lateral(select value own_t from jsonb_array_elements(case when jsonb_typeof(owned->'talents')='array' then owned->'talents' else '[]' end)where value->>'id'=needed->>'id')q on true),0) end),100000)
 from jsonb_array_elements(lineup)slot left join lateral(select value owned from jsonb_array_elements(coalesce(cats,'[]'))where value->>'id'=slot->>'id')q on true
$$;
create function noc_private.list_strategy_guides(payload jsonb)returns jsonb language plpgsql security invoker set search_path='' as $$
declare profile noc_private.game_profiles;match_mode boolean:=coalesce((payload->>'similar')::boolean,false);page_num integer:=coalesce((payload->>'page')::integer,0);stage text:=payload->>'stageKey';outcome_name text:=payload->>'outcome';crown_num integer:=coalesce((payload->>'crown')::integer,0);result jsonb;
begin
 if page_num not between 0 and 500 or crown_num not between 0 and 4 or char_length(coalesce(payload->>'query',''))>100 then raise exception '검색 범위를 확인해 주세요.';end if;
 if match_mode then
  if auth.uid() is null or not noc_private.active_member()then raise exception '로그인과 가입 완료가 필요합니다.';end if;
  select * into profile from noc_private.game_profiles where user_id=auth.uid();if profile.user_id is null or profile.region<>'kr' then raise exception '내 정보에 한국판 캐릭터를 저장해 주세요.';end if;
 end if;
 select coalesce(jsonb_agg(to_jsonb(q)),'[]')into result from(
  select p.id,p.title,p.created_at,p.updated_at,coalesce(m.nickname,'탈퇴한 회원') nickname,g.details as strategy,
  case when match_mode then round(noc_private.guide_distance(g.details->'lineup',profile.cats),2) else null end as distance
  from noc_private.strategy_guides g join noc_private.posts p on p.id=g.post_id left join noc_private.members m on m.id=p.author_id
  where p.status='published' and p.board='guide' and(stage is null or stage='' or g.stage_key=stage)and(crown_num=0 or g.crown=crown_num)and(outcome_name is null or outcome_name='' or g.outcome=outcome_name)and(coalesce(payload->>'query','')='' or p.title ilike '%'||(payload->>'query')||'%')
  order by case when match_mode then noc_private.guide_distance(g.details->'lineup',profile.cats) end asc,p.created_at desc,p.id limit 21 offset page_num*20
 )q;return result;
end$$;
