create schema if not exists noc_private;
revoke all on schema noc_private from public;
grant usage on schema noc_private to anon, authenticated, service_role;
create table noc_private.members (
 id uuid primary key references auth.users(id) on delete cascade,
 nickname text not null check(char_length(nickname) between 2 and 20),
 status text not null default 'pending' check(status in ('pending','active','suspended','deleting')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create unique index members_nickname_lower on noc_private.members(lower(nickname));
create table noc_private.staff (user_id uuid primary key references auth.users(id) on delete cascade, role text not null check(role in ('owner','moderator')));
create table noc_private.consents (id bigint generated always as identity primary key, user_id uuid references auth.users(id) on delete set null, document text not null, version text not null, accepted boolean not null, recorded_at timestamptz not null default now());
create index consents_user on noc_private.consents(user_id);
create table noc_private.characters (key text primary key, name text not null, kind text not null check(kind in ('cat','enemy')));
create table noc_private.posts (
 id uuid primary key default gen_random_uuid(), author_id uuid references auth.users(id) on delete set null,
 board text not null check(board in ('free','question','guide','notice')), title text not null default '' check(char_length(title)<=100),
 body text not null default '' check(char_length(body)<=20000), status text not null default 'draft' check(status in ('draft','published','hidden','deleted')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index posts_published on noc_private.posts(board,created_at desc) where status='published';
create index posts_author on noc_private.posts(author_id);
create table noc_private.comments (
 id uuid primary key default gen_random_uuid(), author_id uuid references auth.users(id) on delete set null,
 post_id uuid references noc_private.posts(id) on delete cascade, character_key text references noc_private.characters(key),
 body text not null check(char_length(body) between 1 and 2000), status text not null default 'published' check(status in ('published','hidden','deleted')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), check(num_nonnulls(post_id,character_key)=1)
);
create index comments_post on noc_private.comments(post_id,created_at) where post_id is not null;
create index comments_character on noc_private.comments(character_key,created_at) where character_key is not null;
create index comments_author on noc_private.comments(author_id);
create table noc_private.ratings (user_id uuid references auth.users(id) on delete cascade, character_key text references noc_private.characters(key), stars smallint not null check(stars between 1 and 5), updated_at timestamptz not null default now(), primary key(user_id,character_key));
create index ratings_character on noc_private.ratings(character_key);
create table noc_private.reports (
 id uuid primary key default gen_random_uuid(), reporter_id uuid references auth.users(id) on delete set null,
 target_type text not null check(target_type in ('post','comment')), target_id uuid not null,
 reason text not null check(char_length(reason) between 5 and 1000), status text not null default 'open' check(status in ('open','resolved','dismissed')),
 snapshot jsonb not null, resolution text, created_at timestamptz not null default now(), resolved_at timestamptz
);
create index reports_reporter on noc_private.reports(reporter_id);
create index reports_queue on noc_private.reports(status,created_at desc);
create unique index reports_one_open on noc_private.reports(reporter_id,target_type,target_id) where status='open';
create table noc_private.notifications (id bigint generated always as identity primary key, user_id uuid references auth.users(id) on delete cascade, message text not null, seen boolean not null default false, created_at timestamptz not null default now());
create index notifications_user on noc_private.notifications(user_id,created_at desc);
create table noc_private.audit (id bigint generated always as identity primary key, actor_id uuid references auth.users(id) on delete set null, action text not null, target_id text, detail jsonb not null default '{}', created_at timestamptz not null default now());
create index audit_created on noc_private.audit(created_at);
create index audit_actor on noc_private.audit(actor_id,created_at desc);
create table noc_private.appeals (id uuid primary key default gen_random_uuid(), user_id uuid references auth.users(id) on delete set null, message text not null check(char_length(message) between 5 and 2000), answer text, status text not null default 'open' check(status in ('open','closed')), created_at timestamptz not null default now());
create index appeals_user on noc_private.appeals(user_id);
create table noc_private.deletion_jobs (user_id uuid primary key references auth.users(id) on delete cascade, requested_at timestamptz not null default now());
-- No data tables are exposed by the public Data API. Defense-in-depth RLS on all private tables.
