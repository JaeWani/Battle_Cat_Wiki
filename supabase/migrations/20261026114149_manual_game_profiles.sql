create or replace function noc_private.game_profile_api(action text,payload jsonb) returns jsonb
language plpgsql security invoker set search_path='' as $$
declare uid uuid:=auth.uid(); previous noc_private.game_profiles; item jsonb; clean_cats jsonb:='[]'; clean_progress jsonb:='[]';
 id_num integer; form_num integer; level_num integer; plus_num integer; n integer; p integer; g integer; version_num integer; cc text; seen integer[]:='{}'; result jsonb; talent jsonb; clean_talents jsonb; talent_id integer; talent_level integer; maximum integer; talent_seen integer[]; source_type text; known_progress boolean;
begin
 if uid is null then raise exception '로그인이 필요해요.';end if;
 if action='game_profile' then
  select jsonb_build_object('schemaVersion',2,'source',source,'progressKnown',progress_known,'gameVersion',game_version,'region',region,'cats',cats,'progress',progress,'updated_at',updated_at) into result from noc_private.game_profiles where user_id=uid;
  return result;
 end if;
 perform pg_advisory_xact_lock(hashtextextended('game-profile:'||uid::text,0));
 select * into previous from noc_private.game_profiles where user_id=uid for update;
 if (payload->>'expected_updated_at')::timestamptz is distinct from previous.updated_at then raise exception '다른 화면에서 데이터가 변경됐어요. 새로고침 후 다시 진행해 주세요.';end if;
 if action='delete_game_profile' then
  delete from noc_private.game_profiles where user_id=uid;
  if previous.user_id is not null then
   insert into noc_private.consents(user_id,document,version,accepted) select uid,'game_data',value->>'policy_version',false from noc_private.settings where key='public';
   insert into noc_private.audit(actor_id,action)values(uid,'game_profile.delete');
  end if;
  return '{"ok":true}';
 end if;
 if action<>'save_game_profile' then raise exception '지원하지 않는 요청이에요.';end if;
 if not noc_private.active_member() then raise exception '가입 완료 및 정상 이용 상태가 필요해요.';end if;
 if not coalesce((payload->>'game_data_accepted')::boolean,false) or (payload->>'policy_version') is distinct from (select value->>'policy_version' from noc_private.settings where key='public') then raise exception '최신 개인정보 안내와 게임 정보 저장 동의를 확인해 주세요.';end if;
 if previous.updated_at>now()-interval '10 seconds' then raise exception '저장 후 10초 뒤 다시 저장할 수 있어요.';end if;
 if octet_length(payload::text)>300000 or jsonb_typeof(payload->'cats') is distinct from 'array' or jsonb_array_length(payload->'cats')>2000 or jsonb_typeof(payload->'progress') is distinct from 'array' or jsonb_array_length(payload->'progress')<>9 then raise exception '게임 정보 크기나 형식이 올바르지 않아요.';end if;
 source_type:=coalesce(payload->>'source','import');known_progress:=coalesce((payload->>'progressKnown')::boolean,true);
 if source_type not in ('import','manual','mixed') then raise exception '올바르지 않은 입력 방식이에요.';end if;
 version_num:=(payload->>'gameVersion')::integer;cc:=payload->>'region';
 if (version_num is null and source_type<>'manual') or (version_num is not null and version_num not between 120000 and 150599) or cc is null or cc not in ('kr','jp','en','tw') then raise exception '지원하지 않는 버전 또는 지역이에요.';end if;
 for item in select value from jsonb_array_elements(payload->'cats') loop
  if jsonb_typeof(item) is distinct from 'object' or not (item ?& array['id','form','level','plus']) or jsonb_typeof(item->'id')<>'number' or jsonb_typeof(item->'form')<>'number' or jsonb_typeof(item->'level')<>'number' or jsonb_typeof(item->'plus')<>'number' then raise exception '캐릭터 항목 형식이 올바르지 않아요.';end if;
  if (item->>'id') !~ '^[0-9]+$' or (item->>'form') !~ '^[0-9]+$' or (item->>'level') !~ '^[0-9]+$' or (item->>'plus') !~ '^[0-9]+$' then raise exception '캐릭터 수치는 정수로 입력해 주세요.';end if;
  id_num:=(item->>'id')::integer;form_num:=(item->>'form')::integer;level_num:=(item->>'level')::integer;plus_num:=(item->>'plus')::integer;
  if id_num is null or form_num is null or level_num is null or plus_num is null or id_num<0 or form_num not between 0 and 3 or level_num not between 1 and 200 or plus_num not between 0 and 1000 or id_num=any(seen) then raise exception '캐릭터 수치 또는 중복 항목을 확인해 주세요.';end if;
  if not exists(select 1 from noc_private.characters where key='c'||id_num::text||'-'||form_num::text and kind='cat') then raise exception '도감에 없는 캐릭터 형태예요.';end if;
  clean_talents:=null;talent_seen:='{}';
  if item ? 'talents' and jsonb_typeof(item->'talents') is distinct from 'null' then
   if jsonb_typeof(item->'talents') is distinct from 'array' or jsonb_array_length(item->'talents')>16 then raise exception '본능 목록 형식이 올바르지 않아요.';end if;
   clean_talents:='[]';
   for talent in select value from jsonb_array_elements(item->'talents') loop
    if jsonb_typeof(talent) is distinct from 'object' or jsonb_typeof(talent->'id') is distinct from 'number' or jsonb_typeof(talent->'level') is distinct from 'number' or (talent->>'id') !~ '^[0-9]+$' or (talent->>'level') !~ '^[0-9]+$' then raise exception '본능 항목 형식이 올바르지 않아요.';end if;
    talent_id:=(talent->>'id')::integer;talent_level:=(talent->>'level')::integer;
    select max_level into maximum from noc_private.character_talents where cat_id=id_num and ability_id=talent_id;
    if maximum is null or talent_level not between 0 and maximum or talent_id=any(talent_seen) then raise exception '해당 캐릭터의 본능 종류·레벨·중복을 확인해 주세요.';end if;
    talent_seen:=array_append(talent_seen,talent_id);
    clean_talents:=clean_talents||jsonb_build_array(jsonb_build_object('id',talent_id,'level',talent_level));
   end loop;
  elsif source_type='import' then
   select value->'talents' into clean_talents from jsonb_array_elements(coalesce(previous.cats,'[]')) where (value->>'id')::integer=id_num;
  end if;
  seen:=array_append(seen,id_num);clean_cats:=clean_cats||jsonb_build_array(jsonb_build_object('id',id_num,'form',form_num,'level',level_num,'plus',plus_num,'talents',clean_talents));
 end loop;
 for item in select value from jsonb_array_elements(payload->'progress') loop
  if jsonb_typeof(item) is distinct from 'object' or not (item ?& array['progress','cleared','gold']) or jsonb_typeof(item->'progress')<>'number' or jsonb_typeof(item->'cleared')<>'number' or jsonb_typeof(item->'gold')<>'number' then raise exception '진행 정보 형식이 올바르지 않아요.';end if;
  p:=(item->>'progress')::integer;n:=(item->>'cleared')::integer;g:=(item->>'gold')::integer;
  if p is null or n is null or g is null or p not between 0 and 51 or n not between 0 and 48 or g not between 0 and 48 then raise exception '진행 정보 수치를 확인해 주세요.';end if;
  clean_progress:=clean_progress||jsonb_build_array(jsonb_build_object('progress',p,'cleared',n,'gold',g));
 end loop;
 insert into noc_private.game_profiles(user_id,game_version,region,cats,progress,source,progress_known,updated_at)values(uid,version_num,cc,clean_cats,clean_progress,source_type,known_progress,clock_timestamp())
 on conflict(user_id) do update set game_version=excluded.game_version,region=excluded.region,cats=excluded.cats,progress=excluded.progress,source=excluded.source,progress_known=excluded.progress_known,updated_at=excluded.updated_at;
 insert into noc_private.consents(user_id,document,version,accepted) select uid,'game_data',value->>'policy_version',true from noc_private.settings where key='public';
 insert into noc_private.audit(actor_id,action,detail)values(uid,'game_profile.'||source_type,jsonb_build_object('cat_count',jsonb_array_length(clean_cats),'version',version_num,'region',cc));
 return noc_private.game_profile_api('game_profile','{}');
end $$;
